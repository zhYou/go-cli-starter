package main

import (
	"os"
	"path/filepath"
	"testing"

	"github.com/stretchr/testify/require"
)

func TestCheckPackageDocumentation(t *testing.T) {
	for _, tc := range []struct {
		name  string
		files map[string]string
		want  string
	}{
		{"documented", map[string]string{
			"internal/feature/doc.go":           "// Package feature 校验用户输入。\npackage feature\n",
			"internal/feature/run.go":           "package feature\nfunc Run() {}\n",
			"internal/feature/run_test.go":      "package feature\n",
			"internal/feature/external_test.go": "package feature_test\n",
		}, ""},
		{"command", map[string]string{
			"cmd/tool/doc.go":  "// Tool 提供命令行入口。\npackage main\n",
			"cmd/tool/main.go": "package main\nfunc main() {}\n",
		}, ""},
		{"test package", map[string]string{
			"test/integration/doc.go":          "// Package integration 验证真实进程。\npackage integration\n",
			"test/integration/process_test.go": "package integration\n",
		}, ""},
		{"test package missing documentation", map[string]string{
			"test/integration/process_test.go": "package integration\n",
		}, "test/integration/doc.go"},
		{"external test only", map[string]string{"external_test.go": "package feature_test\n"}, ""},
		{"missing", map[string]string{"feature.go": "package feature\n"}, "缺少 doc.go"},
		{"inline instead of doc.go", map[string]string{"feature.go": "// Package feature 校验输入。\npackage feature\n"}, "缺少 doc.go"},
		{"empty", map[string]string{"doc.go": "package feature\n"}, "包说明不能为空"},
		{"name only", map[string]string{"doc.go": "// Package feature\npackage feature\n"}, "包说明不能为空"},
		{"punctuation placeholder", map[string]string{"doc.go": "// Package feature\n// .\npackage feature\n"}, "包说明不能为空"},
		{"symbol placeholder", map[string]string{"doc.go": "// Package feature\n// _ !!!\npackage feature\n"}, "包说明不能为空"},
		{"detached comment", map[string]string{"doc.go": "// Package feature 校验输入。\n\npackage feature\n"}, "包说明不能为空"},
		{"different package", map[string]string{
			"doc.go":     "// Package other 描述另一个包。\npackage other\n",
			"feature.go": "package feature\n",
		}, "包名不一致"},
		{"duplicate", map[string]string{
			"doc.go":     "// Package feature 校验输入。\npackage feature\n",
			"feature.go": "// Package feature 重复说明。\npackage feature\n",
		}, "包说明必须集中在 doc.go"},
		{"test comments ignored", map[string]string{
			"doc.go":          "// Package feature 校验输入。\npackage feature\n",
			"feature_test.go": "// 测试文件的说明。\npackage feature\n",
		}, ""},
		{"function", map[string]string{"doc.go": "// Package feature 校验输入。\npackage feature\nfunc Run() {}\n"}, "只能包含包说明和 package 声明"},
		{"import", map[string]string{"doc.go": "// Package feature 校验输入。\npackage feature\nimport _ \"fmt\"\n"}, "只能包含包说明和 package 声明"},
		{"variable", map[string]string{"doc.go": "// Package feature 校验输入。\npackage feature\nvar Value = 1\n"}, "只能包含包说明和 package 声明"},
		{"constant", map[string]string{"doc.go": "// Package feature 校验输入。\npackage feature\nconst Value = 1\n"}, "只能包含包说明和 package 声明"},
		{"type", map[string]string{"doc.go": "// Package feature 校验输入。\npackage feature\ntype Value int\n"}, "只能包含包说明和 package 声明"},
		{"platform source", map[string]string{"platform_windows.go": "//go:build windows\n\npackage platform\n"}, "缺少 doc.go"},
		{"platform duplicate", map[string]string{
			"doc.go":              "// Package platform 封装系统能力。\npackage platform\n",
			"platform_windows.go": "//go:build windows\n\n// Package platform 重复说明。\npackage platform\n",
		}, "包说明必须集中在 doc.go"},
		{"generated", map[string]string{"generated.go": "// Code generated by fixture. DO NOT EDIT.\npackage generated\n"}, ""},
		{"generated with handwritten source", map[string]string{
			"generated.go": "// Code generated by fixture. DO NOT EDIT.\npackage feature\n",
			"feature.go":   "package feature\n",
		}, "缺少 doc.go"},
		{"generated doc cannot satisfy handwritten package", map[string]string{
			"doc.go":     "// Code generated by fixture. DO NOT EDIT.\n\n// Package feature 自动生成说明。\npackage feature\n",
			"feature.go": "package feature\n",
		}, "缺少 doc.go"},
		{"invalid syntax", map[string]string{"feature.go": "package\n"}, "feature.go"},
		{"ignored directories", map[string]string{
			".worktrees/task/invalid.go":       "invalid",
			".git/invalid.go":                  "invalid",
			"_scratch/invalid.go":              "invalid",
			"vendor/invalid.go":                "invalid",
			"tools/lint/testdata/invalid.go":   "invalid",
			"bin/invalid.go":                   "invalid",
			"docs/superpowers/task/invalid.go": "invalid",
			"dist/invalid.go":                  "invalid",
			"_ignored.go":                      "invalid",
			".ignored.go":                      "invalid",
		}, ""},
		{"package named bin is not build output", map[string]string{"internal/bin/bin.go": "package bin\n"}, "internal/bin/doc.go"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			root := t.TempDir()
			for name, data := range tc.files {
				path := filepath.Join(root, filepath.FromSlash(name))
				require.NoError(t, os.MkdirAll(filepath.Dir(path), 0o700))
				require.NoError(t, os.WriteFile(path, []byte(data), 0o600))
			}
			err := checkDocumentation(root)
			if tc.want == "" {
				require.NoError(t, err)
			} else {
				require.ErrorContains(t, err, tc.want)
			}
		})
	}
}

func TestCheckRejectsMissingRoot(t *testing.T) {
	require.Error(t, checkDocumentation(filepath.Join(t.TempDir(), "missing")))
}

func TestCheckRejectsLinkedDocumentation(t *testing.T) {
	root := t.TempDir()
	require.NoError(t, os.WriteFile(filepath.Join(root, "feature.go"), []byte("package feature\n"), 0o600))
	outside := filepath.Join(t.TempDir(), "outside.go")
	require.NoError(t, os.WriteFile(outside, []byte("// Package feature 外部说明。\npackage feature\n"), 0o600))
	if err := os.Symlink(outside, filepath.Join(root, "doc.go")); err != nil {
		t.Skipf("当前平台无法创建符号链接：%v", err)
	}
	require.ErrorContains(t, checkDocumentation(root), "不是普通文件")
}
