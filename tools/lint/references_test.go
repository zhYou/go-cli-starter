func TestDiagnosticReferences(t *testing.T) {
	tests := []struct {
		name    string
		body    string
		missing string
	}{
		{"literal", `var _ = f.Definition{Code: "known", Kind: "runtime"}`, ""},
		{"missing definition", `var _ = f.Definition{Code: "missing"}`, "missing"},
		{"missing recovery", `var _ = &f.Recovery{Code: "recover.missing"}`, "recover.missing"},
		{"constant expression", `const suffix = "nown"; var _ = f.Definition{Code: f.Code("k" + suffix)}`, ""},
		{"missing constant", `const id = "missing.const"; var _ = f.Definition{Code: f.Code(id)}`, "missing.const"},
		{"type alias", `type D = f.Definition; var _ = D{Code: "alias.missing"}`, "alias.missing"},
		{"unkeyed", `var _ = f.Recovery{"unkeyed.missing", nil}`, "unkeyed.missing"},
		{"assignment", `func change(d *f.Definition) { d.Code = "assigned.missing" }`, "assigned.missing"},
		{
			"parenthesized assignment",
			`func change(d *f.Definition) { (d.Code) = "parenthesized.missing" }`,
			"parenthesized.missing",
		},
		{
			"promoted assignment",
			`type W struct { f.Definition }; func change(d *W) { d.Code = "promoted.missing" }`,
			"promoted.missing",
		},
		{
			"nested promoted recovery",
			`type Inner struct { *f.Recovery }; type W struct { Inner }; func change(d *W) { d.Code = "nested.missing" }`,
			"nested.missing",
		},
		{
			"unrelated promoted field",
			`type Other struct { Code string }; type W struct { Other }; func change(d *W) { d.Code = "unrelated" }; var _ f.Definition`,
			"",
		},
		{"recovery assignment", `func change(d *f.Recovery) { d.Code = "assigned.missing" }`, "assigned.missing"},
		{
			"unrelated type",
			`type Recovery struct { Code string }; var _ = Recovery{Code: "unrelated"}; var _ f.Definition`,
			"",
		},
		{
			"dynamic",
			`func define(code string) f.Definition { return f.Definition{Code: f.Code("dynamic." + code)} }`,
			"",
		},
		{"empty projection", `var _ = f.Definition{Kind: "runtime"}; var _ = f.Definition{Code: ""}`, ""},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			root := referenceProject(t, tt.body)
			err := checkDiagnosticReferences(t.Context(), root, map[string]bool{"known": true})
			if tt.missing == "" {
				require.NoError(t, err)
				return
			}
			require.ErrorContains(t, err, tt.missing)
			require.Contains(t, err.Error(), "internal/feature/feature.go:")
			require.NotContains(t, err.Error(), root)
		})
	}
}

func TestDiagnosticReferencesExclusionsAndReadOnly(t *testing.T) {
	root := referenceProject(t, `var _ = f.Definition{Code: "known"}`)
	generated := "// Code generated by fixture. DO NOT EDIT.\npackage feature\nimport f \"example.com/derived/internal/base/fault\"\nvar _ = f.Recovery{Code: \"generated.missing\"}\n"
	require.NoError(t, os.WriteFile(filepath.Join(root, "internal/feature/generated.go"), []byte(generated), 0o600))
	require.NoError(
		t,
		os.WriteFile(
			filepath.Join(root, "internal/feature/feature_test.go"),
			[]byte("package feature\nvar _ = undefinedTestOnly\n"),
			0o600,
		),
	)
	//nolint:gosec // G304：路径来自本测试创建的临时项目。
	module, err := os.ReadFile(filepath.Join(root, moduleFile))
	require.NoError(t, err)
	require.NoError(t, checkDiagnosticReferences(t.Context(), root, map[string]bool{"known": true}))
	//nolint:gosec // G304：路径来自本测试创建的临时项目。
	after, err := os.ReadFile(filepath.Join(root, moduleFile))
	require.NoError(t, err)
	require.Equal(t, module, after)
	_, err = os.Stat(filepath.Join(root, "go.sum"))
	require.True(t, os.IsNotExist(err))
}

func TestDiagnosticReferencesReportsLoadFailureAndCancellation(t *testing.T) {
	root := referenceProject(t, `var _ = f.Definition{Code: undefined}`)
	require.Error(t, checkDiagnosticReferences(t.Context(), root, nil))
	ctx, cancel := context.WithCancel(t.Context())
	cancel()
	err := checkDiagnosticReferences(ctx, root, nil)
	require.ErrorIs(t, err, context.Canceled)
}

func TestDiagnosticReferencesStableDiagnostics(t *testing.T) {
	root := referenceProject(
		t,
		"var _ = f.Definition{Code: \"first.missing\"}\nvar _ = f.Recovery{Code: \"second.missing\"}",
	)
	first := checkDiagnosticReferences(t.Context(), root, nil)
	second := checkDiagnosticReferences(t.Context(), root, nil)
	require.Error(t, first)
	require.EqualError(t, second, first.Error())
	require.Less(t, strings.Index(first.Error(), "first.missing"), strings.Index(first.Error(), "second.missing"))
}

func TestProjectMessagesChecksCatalogAndReferences(t *testing.T) {
	root := referenceProject(t, `var _ = f.Definition{Code: "missing"}`)
	require.ErrorContains(t, checkProjectMessages(t.Context(), root, pair(`["known"]
other = "Known"
`, `["known"]
other = "已知"
`)), "missing")
	require.ErrorContains(t, checkProjectMessages(t.Context(), root, fstest.MapFS{}), "消息")
}

func TestI18nTaskRejectsUntranslatedReference(t *testing.T) {
	root := referenceProject(t, `var _ = f.Recovery{Code: "missing.from.both"}`)
	t.Chdir(root)
	require.ErrorContains(t, run([]string{"i18n"}), "missing.from.both")
}
