package main

import (
	"os"
	"path/filepath"
	"testing"

	"github.com/stretchr/testify/require"
)

func TestCheckStyle(t *testing.T) {
	for _, tc := range []struct {
		name  string
		files map[string]string
		want  string
	}{
		{"named", map[string]string{"feature.go": "package feature\ntype Value struct { A, B string }\n"}, "feature.go:2: 结构体字段须逐项声明：A, B"},
		{"anonymous", map[string]string{"feature_test.go": "package feature\nvar cases = []struct { input, want string }{}\n"}, "input, want"},
		{"generic", map[string]string{"generic.go": "package feature\ntype Pair[T any] struct { Left, Right T }\n"}, "Left, Right"},
		{"platform", map[string]string{"feature_windows.go": "//go:build windows\n\npackage feature\ntype Value struct { A, B uintptr }\n"}, "feature_windows.go:4:"},
		{"external test", map[string]string{"external_test.go": "package feature_test\nvar cases = []struct { A, B int }{}\n"}, "A, B"},
		{"separate fields and grouped parameters", map[string]string{"feature.go": "package feature\ntype Value struct { A string; B string; *Other }\nfunc F(a, b string) (x, y int) { return }\n"}, ""},
		{"generated", map[string]string{"generated.go": "// Code generated by fixture. DO NOT EDIT.\npackage feature\ntype Value struct { A, B string }\n"}, ""},
		{"ignored", map[string]string{
			"testdata/invalid.go": "invalid", "vendor/invalid.go": "invalid",
			".hidden/invalid.go": "invalid", "_scratch/invalid.go": "invalid",
			"bin/invalid.go": "invalid", "dist/invalid.go": "invalid",
			"docs/superpowers/task/invalid.go": "invalid", ".hidden.go": "invalid", "_scratch.go": "invalid",
		}, ""},
		{"nested bin", map[string]string{"internal/bin/value.go": "package bin\ntype Value struct { A, B string }\n"}, "A, B"},
		{"parse error", map[string]string{"invalid.go": "package\n"}, "解析 invalid.go"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			root := t.TempDir()
			for name, source := range tc.files {
				path := filepath.Join(root, filepath.FromSlash(name))
				require.NoError(t, os.MkdirAll(filepath.Dir(path), 0o700))
				require.NoError(t, os.WriteFile(path, []byte(source), 0o600))
			}
			err := checkStyle(root)
			if tc.want == "" {
				require.NoError(t, err)
			} else {
				require.ErrorContains(t, err, tc.want)
			}
		})
	}
}

func TestStyleRejectsMissingRoot(t *testing.T) {
	require.Error(t, checkStyle(filepath.Join(t.TempDir(), "missing")))
}

func TestStyleRejectsLinkedSource(t *testing.T) {
	root := t.TempDir()
	outside := filepath.Join(t.TempDir(), "outside.go")
	require.NoError(t, os.WriteFile(outside, []byte("package feature\n"), 0o600))
	if err := os.Symlink(outside, filepath.Join(root, "linked.go")); err != nil {
		t.Skipf("当前平台无法创建符号链接：%v", err)
	}
	require.ErrorContains(t, checkStyle(root), "不是普通文件")
}

func TestStyleTaskReportsGroupedFields(t *testing.T) {
	t.Chdir(t.TempDir())
	require.NoError(
		t,
		os.WriteFile("feature.go", []byte("package feature\ntype Value struct { A, B string }\n"), 0o600),
	)
	require.ErrorContains(t, run([]string{"style"}), "A, B")
}
